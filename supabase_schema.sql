-- Updated schema for dashboard with user authentication and analytics

-- Create invites table with analytics tracking
create table invites (
  id bigint generated by default as identity primary key,
  token text unique not null,
  user_id uuid references auth.users(id) on delete cascade, -- Owner of this URL
  recipient_name text not null, -- e.g., "Sakshi"
  first_opened_at timestamp with time zone, -- When first viewed
  total_visits integer default 0, -- Count of page loads
  visit_timestamps timestamp with time zone[] default '{}', -- Array of all visit timestamps
  no_clicks integer default 0, -- Count of "No" button clicks
  yes_timestamps timestamp with time zone[] default '{}', -- Array of all "Yes" click timestamps
  first_yes_at timestamp with time zone, -- When "Yes" was clicked for the very first time
  used boolean default false, -- "Yes" clicked?
  used_at timestamp with time zone, -- When "Yes" was clicked (Latest)
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Index for faster lookups
create index idx_invites_token on invites(token);
create index idx_invites_user_id on invites(user_id);

-- Enable RLS (Row Level Security)
alter table invites enable row level security;

-- RLS Policies

-- Users can only see their own invites
create policy "Users can view own invites"
on invites for select
using (auth.uid() = user_id);

-- Users can only create invites for themselves
create policy "Users can create own invites"
on invites for insert
with check (auth.uid() = user_id);

-- Users can update their own invites
create policy "Users can update own invites"
on invites for update
using (auth.uid() = user_id);

-- Allow users to delete their own created URLs
create policy "Users can delete own invites"
on invites for delete
using (auth.uid() = user_id);


-- SECURE ANALYTICS FUNCTIONS (RPCs)
-- These allow updating analytics without exposing public table access.
-- They run as the function owner (security definer), so each one pins `search_path`:
-- without it a caller could shadow `invites` / `now()` with their own objects in a schema
-- earlier on their search path and have this code run against them with elevated rights.
-- All of these use `create or replace`, so re-running this section on an existing project
-- is safe and is how to pick up changes.

-- Helper: append to a timestamp array but keep only the newest `max_len` entries.
-- Without a cap the visit / yes arrays grew forever (every page load adds an element), so a link that
-- is opened or refreshed thousands of times - by a bot, or just a very keen recipient - made its row
-- ever larger and every dashboard refresh heavier. The exact totals are NOT lost: `total_visits` is a
-- separate counter, and `first_opened_at` / `first_yes_at` are stored separately; only the oldest
-- entries of the history list are dropped. It also trims rows that are already over the limit the next
-- time they are touched, so existing data heals itself.
create or replace function append_capped(arr timestamp with time zone[], item timestamp with time zone, max_len int)
returns timestamp with time zone[] as $$
  select case
    when coalesce(cardinality(arr), 0) >= max_len
      then (arr || item)[cardinality(arr) + 2 - max_len : cardinality(arr) + 1]
    else coalesce(arr, '{}'::timestamp with time zone[]) || item
  end
$$ language sql immutable;

-- 1. Secure function to track visits (handles timestamps + counter)
create or replace function track_visit(url_token text)
returns void as $$
begin
  update invites
  set 
    total_visits = total_visits + 1,
    visit_timestamps = append_capped(visit_timestamps, now(), 200),
    first_opened_at = coalesce(first_opened_at, now())
  where token = url_token;
end;
$$ language plpgsql security definer set search_path = public;

-- 2. Secure function to track "Yes" response
create or replace function track_yes(url_token text)
returns void as $$
begin
  update invites
  set 
    used = true,
    used_at = now(),
    yes_timestamps = append_capped(yes_timestamps, now(), 50),
    first_yes_at = coalesce(first_yes_at, now()),
    first_opened_at = coalesce(first_opened_at, now()) -- Fix race condition: ensure opened_at exists
  where token = url_token;
end;
$$ language plpgsql security definer set search_path = public;

-- 3. Secure function to track "No" clicks
create or replace function track_no(url_token text)
returns void as $$
begin
  update invites
  set no_clicks = no_clicks + 1
  where token = url_token;
end;
$$ language plpgsql security definer set search_path = public;

-- 4. Secure function to check if invite exists (returns bool)
create or replace function check_invite_exists(url_token text)
returns boolean as $$
begin
  return exists(select 1 from invites where token = url_token);
end;
$$ language plpgsql security definer set search_path = public;


-- 5. Let a signed-in user delete their own account (used by the dashboard's "Delete Forever").
-- The browser cannot delete an auth user directly; this removes the caller's row from
-- auth.users, and the `on delete cascade` on invites.user_id removes all of their invites.
-- Until this function exists the dashboard falls back to only deleting the user's invites.
create or replace function delete_my_account()
returns void as $$
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  delete from auth.users where id = auth.uid();
end;
$$ language plpgsql security definer set search_path = public, auth;

revoke all on function delete_my_account() from public, anon;
grant execute on function delete_my_account() to authenticated;


-- REALTIME
-- The dashboard subscribes to changes on `invites` so new visits / "Yes" answers show up
-- without a refresh. Postgres changes are only broadcast for tables in this publication.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'invites'
  ) then
    alter publication supabase_realtime add table public.invites;
  end if;
end
$$;
